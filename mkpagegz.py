#!/usr/bin/env python3
"""generates control_page_gz.h: the control_page.h page compressed with gzip, to be served with \"Content-Encoding: gzip\".
After decompression the page is identical to the one in control_page.h except for two lines, which are needed because the security code changes at every boot
and cannot be inside the compressed bytes:
  - in the head <script src=\"/t.js\"> is called (the board serves it uncompressed and it contains the boot code: window.NB_T=\"...\");
  - the line   const T=\"@@TOKEN@@\";   becomes   const T=window.NB_T;
Usage: mkpagegz.py [--check]    (--check verifies that the compressed bytes decompress into the expected page and writes nothing)"""
import gzip, re, sys, zlib

SRC = "control_page.h"
OUT = "control_page_gz.h"
t = open(SRC, encoding="utf-8").read()
m = re.search(r'R"HTML\((.*)\)HTML"', t, re.S)
if not m:
    sys.exit("mkpagegz: the page is not between R\"HTML( and )HTML\"")
page = m.group(1)
assert page.count('const T="@@TOKEN@@";') == 1, "mkpagegz: the code placeholder must appear only once"
assert page.count("<head>") == 1
assert page.count("@@TOKEN@@") == 1
final = page.replace('const T="@@TOKEN@@";', "const T=window.NB_T;").replace("<head>", '<head><script src="/t.js"></script>', 1)
data = final.encode("utf-8")
gz = gzip.compress(data, 9, mtime=0)
if "--check" in sys.argv:
    assert gzip.decompress(gz) == data
    print("ok: %d bytes of page -> %d bytes compressed (%.0f%%)" % (len(data), len(gz), 100.0 * len(gz) / len(data)))
    sys.exit(0)
lines = []
for i in range(0, len(gz), 24):
    lines.append("\t" + ",".join(str(b) for b in gz[i:i + 24]))
body = ",\n".join(lines)
open(OUT, "w", encoding="utf-8", newline="\n").write(
    "// control_page_gz.h - GENERATED by mkpagegz.py from control_page.h: do not edit by hand\n"
    "#define PAGE_GZ_RAW_LEN %d\n"
    "static const unsigned char s_PageGz[] = {\n%s\n};\n" % (len(data), body))
print("control_page_gz.h: %d bytes of page -> %d bytes compressed (%.0f%%)" % (len(data), len(gz), 100.0 * len(gz) / len(data)))
